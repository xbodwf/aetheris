package dev.aetheris.engine.data

import dev.aetheris.engine.chem.CombustionTemplate
import dev.aetheris.engine.chem.Formula
import dev.aetheris.engine.chem.Mixture
import dev.aetheris.engine.chem.Phase
import dev.aetheris.engine.chem.ReactionEngine
import dev.aetheris.engine.chem.SpeciesRegistry
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Assumptions.assumeTrue
import org.junit.jupiter.api.Test
import java.io.File

/**
 * End-to-end check against the *real* converted NASA catalogue, not a fixture.
 *
 * This is the test that would catch a converter regression: it fails if any of the ~700
 * generated formulas cannot be parsed, or if any auto-generated reaction breaks the element
 * or charge conservation invariant the engine enforces at construction.
 *
 * Converted data is regenerated by `tools/convert_nasa.py`; if it has not been generated the
 * test is skipped rather than failed.
 */
class RealDataIntegrationTest {

    private fun locateSpeciesData(): File? {
        var dir = File(System.getProperty("user.dir")).absoluteFile
        repeat(5) {
            val candidate = File(dir, "common/src/main/resources/data/aetheris/species/nasa_gas.json")
            if (candidate.isFile) return candidate
            dir = dir.parentFile ?: return null
        }
        return null
    }

    @Test
    fun `the real catalogue loads and every generated reaction is balanced`() {
        val file = locateSpeciesData()
        assumeTrue(file != null, "converted NASA data not present; run tools/convert_nasa.py")

        val registry = SpeciesRegistry()
        val species = SpeciesCodec.load(file!!.readText(), registry)
        assertTrue(species.size > 500, "expected a large catalogue, got ${species.size}")

        // Constructing the engine runs Conservation.requireBalanced on every reaction.
        val reactions = CombustionTemplate().instantiate(registry)
        assertTrue(reactions.size > 50, "expected many templated reactions, got ${reactions.size}")
        val engine = ReactionEngine(registry, reactions)

        // And a real fuel from the data actually burns.
        val methane = registry.byFormula(Formula.parse("CH4"), Phase.GAS).first()
        val oxygen = registry.byFormula(Formula.parse("O2"), Phase.GAS).first()
        val mixture = Mixture(registry, 1.0, 1000.0, mapOf(methane.id to 1.0, oxygen.id to 2.0))

        val report = engine.step(mixture, 0.1)
        assertTrue(report.reacted, "methane from the NASA data should combust at 1000 K")
        assertTrue(mixture.amount(methane.id) < 1.0)
        assertTrue(mixture.temperature > 1000.0)
    }
}
