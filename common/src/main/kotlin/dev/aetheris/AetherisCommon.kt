package dev.aetheris

import dev.aetheris.engine.chem.CombustionTemplate
import dev.aetheris.engine.chem.ReactionEngine
import dev.aetheris.engine.chem.ReactionTemplate
import dev.aetheris.engine.chem.SpeciesRegistry
import dev.aetheris.engine.chem.WetChemistry
import dev.aetheris.engine.data.SpeciesCodec

/**
 * The one place shared by both loaders where the simulation is assembled from data.
 *
 * This is deliberately thin: it owns no loader types and does no I/O of its own beyond reading
 * one resource, so the same wiring can be tested outside Minecraft. Species come from the
 * converted NASA thermodynamic database rather than a hand-written list; only the reaction
 * *rules* ([ReactionTemplate]) are code, and even those expand into hundreds of reactions.
 */
object AetherisCommon {

    /**
     * Species data. The NASA catalogue is generated by `tools/convert_nasa.py`; the aqueous slice
     * (ions and sparingly soluble salts) is hand-curated because the NASA *gas* set has none.
     */
    private val SPECIES_DATA = listOf(
        "/data/aetheris/species/nasa_gas.json",
        "/data/aetheris/species/aqueous.json",
        "/data/aetheris/species/nist.json",
    )

    /** Templates are the anti-hardcoding mechanism: one rule covers a whole family of reactions. */
    private val templates: List<ReactionTemplate> = listOf(
        CombustionTemplate(),
        WetChemistry.precipitation,
    )

    /** The default simulation: species from data, reactions from templates. */
    val chemistry: ReactionEngine by lazy {
        val registry = SpeciesRegistry()
        for (path in SPECIES_DATA) SpeciesCodec.load(readSpeciesData(path), registry)
        val reactions = templates.flatMap { it.instantiate(registry) }
        ReactionEngine(registry, reactions)
    }

    private fun readSpeciesData(path: String): String =
        AetherisCommon::class.java.getResourceAsStream(path)
            ?.bufferedReader()
            ?.use { it.readText() }
            ?: error("Aetheris species data is missing from the mod jar: $path")
}
